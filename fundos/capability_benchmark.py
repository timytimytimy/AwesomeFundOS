def capability_snapshot(root: Path, candidate_id: str, stage: str) -> dict[str, Any]:
    skill_path = root / "skills" / DEFAULT_AGENT_ID / "SKILL.md"
    text = skill_path.read_text(encoding="utf-8") if skill_path.exists() else ""
    registry_rows = read_jsonl(root / "memory" / "agents" / DEFAULT_AGENT_ID / "capabilities" / "skill.jsonl")
    row = next((item for item in registry_rows if item.get("candidate_id") == candidate_id), {})
    marker_present = f"FUNDOS_CAPABILITY:{candidate_id} START" in text
    return {
        "stage": stage,
        "candidate_id": candidate_id,
        "application_status": row.get("application_status"),
        "regression_status": row.get("regression_status"),
        "managed_skill_block_present": marker_present,
        "skill_path_exists": skill_path.exists(),
        "skill_text_length": len(text),
        "source_agent_card_mutated": False,
        "real_trade_allowed": False,
        "broker_integration": "disabled",
    }


def compare_snapshots(before: dict[str, Any], after: dict[str, Any]) -> dict[str, Any]:
    issues: list[str] = []
    if before.get("managed_skill_block_present"):
        issues.append("baseline_already_had_managed_skill_block")
    if not after.get("managed_skill_block_present"):
        issues.append("after_apply_missing_managed_skill_block")
    if after.get("application_status") != "applied":
        issues.append("after_apply_status_not_applied")
    if after.get("source_agent_card_mutated"):
        issues.append("source_agent_card_mutated")
    if after.get("real_trade_allowed") is not False or after.get("broker_integration") != "disabled":
        issues.append("safety_boundary_violation")
    return {
        "managed_skill_block_added": not before.get("managed_skill_block_present") and after.get("managed_skill_block_present"),
        "application_status_transition": f"{before.get('application_status')}->{after.get('application_status')}",
        "skill_text_length_delta": int(after.get("skill_text_length", 0) or 0) - int(before.get("skill_text_length", 0) or 0),
        "benchmark_passed": not issues,
        "blocking_issues": issues,
    }


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def remove_tree(path: Path) -> None:
    for child in sorted(path.rglob("*"), reverse=True):
        if child.is_file() or child.is_symlink():
            child.unlink()
        elif child.is_dir():
            child.rmdir()
    path.rmdir()
