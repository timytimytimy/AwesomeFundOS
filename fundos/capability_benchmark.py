CAPABILITY_BENCHMARK_VERSION = "0.1.0"
FIXTURE_ID = "capability_benchmark_skill_apply_fixture_v1"


DEFAULT_AGENT_ID = "position_trend_trader"


def run_capability_benchmark_fixture(root: Path, fixture_name: str = FIXTURE_ID) -> dict[str, Any]:
    workspace = root / "runs" / fixture_name
    run_path = workspace / "runs" / "capability-benchmark-fixture"
    if workspace.exists():
        # Keep benchmark deterministic and isolated from prior runs, including
        # runtime skills and memory registries generated by previous applies.
        remove_tree(workspace)
    run_path.mkdir(parents=True, exist_ok=True)
    for name in ["harness", "evidence", "evaluations", "context", "agent_work", "evolution", "learning", "system"]:
        (run_path / name).mkdir(parents=True, exist_ok=True)
    agent = load_roster_agent(root, DEFAULT_AGENT_ID)

    pack = make_evidence_pack(
        "capability-benchmark-fixture",
        "topic",
        "能力升级基准测试：事件催化后的量价确认 checklist",
        public_results=[
            {
                "title": "公告样例：事件催化后订单确认",
                "url": "https://www.cninfo.com.cn/new/disclosure/detail/capability-benchmark",
                "snippet": "公告披露事件催化后的订单确认，但仍需量价和风险边界确认。",
                "source_type": "announcement",
                "source_tier": "tier_1_primary_fact",
                "fixture_category": "announcement",
            },
            {
                "title": "行情样例：事件催化后高开回落",
                "url": "https://example.com/market/capability-benchmark",
                "snippet": "离线行情显示事件催化后高开回落，交易 checklist 需要加入量价确认、失效条件和仓位上限。",
                "source_type": "market_data",
                "source_tier": "tier_1_primary_fact",
                "fixture_category": "market_data",
            },
        ],
    )
    write_yaml(run_path / "evidence" / "evidence-pack.yaml", pack)
    selected = [{"agent_id": agent["id"], "role": agent["role"]}]
    write_yaml(run_path / "run.yaml", {"run_id": run_path.name, "selected_agents": selected, "model_records": [], "real_trade_allowed": False, "broker_integration": "disabled"})
    context = make_context_pack(run_path.name, agent, pack, runtime_root=workspace)
    write_yaml(run_path / "context" / f"{agent['id']}.context-pack.yaml", context)
    write_agent_output(run_path / "agent_work" / f"{agent['id']}.md", agent, context, pack["query"], pack)
    write_replay_pattern(run_path, agent)
    write_operating_system_manifest(run_path, repo_root=root)
    case_replay = run_case_replay(run_path)
    agent_harness = evaluate_agent_harness(run_path, selected)
    write_yaml(run_path / "harness" / "agent-harness.yaml", agent_harness)
    evaluation = make_evaluation_for_run(run_path.name, selected, pack, run_path)
    write_yaml(run_path / "evaluations" / "evaluation-report.yaml", evaluation)

    registry = workspace / "memory" / "agents" / agent["id"] / "capabilities" / "skill.jsonl"
    candidate = fixture_candidate(run_path.name)
    append_jsonl(registry, [candidate])
    regression = run_capability_regression(run_path, root=workspace)
    skill_benchmark = run_skill_benchmark(run_path)
    before_snapshot = capability_snapshot(workspace, candidate["candidate_id"], "before_apply")
    apply_result = apply_approved_capability(workspace, candidate["candidate_id"], approver="benchmark-fixture-human")
    after_snapshot = capability_snapshot(workspace, candidate["candidate_id"], "after_apply")
    improvement = compare_snapshots(before_snapshot, after_snapshot)
    report = {
        "version": CAPABILITY_BENCHMARK_VERSION,
        "artifact_type": "capability_benchmark_fixture_report",
        "fixture_id": FIXTURE_ID,
        "run_id": run_path.name,
        "workspace_path": workspace.relative_to(root).as_posix() if workspace.is_relative_to(root) else str(workspace),
        "candidate_id": candidate["candidate_id"],
        "target_agent": agent["id"],
        "capability_kind": "skill",
        "baseline": before_snapshot,
        "after_apply": after_snapshot,
        "improvement": improvement,
        "case_replay_score": case_replay.get("case_replay_score", 0),
        "regression_status": regression.get("regression_status"),
        "skill_benchmark_status": skill_benchmark.get("capability_candidate_results", [{}])[0].get("skill_benchmark_status") if skill_benchmark.get("capability_candidate_results") else "missing",
        "application_status": apply_result.get("application_status"),
        "applied_target_path": apply_result.get("target_path"),
        "status": "passed" if improvement["benchmark_passed"] else "blocked",
        "blocking_issues": improvement["blocking_issues"],
        "controls": [
            "capability_benchmark_fixture",
            "before_after_apply_comparison",
            "regression_required_before_apply",
            "skill_benchmark_required_before_apply",
            "human_approval_required",
            "no_real_trade_action",
            "broker_integration_disabled",
        ],
        "real_trade_allowed": False,
        "broker_integration": "disabled",
    }
    write_yaml(run_path / "harness" / "capability-benchmark-fixture.yaml", report)
    return report


def load_roster_agent(root: Path, agent_id: str) -> dict[str, Any]:
    roster = read_yaml(root / "specs" / "agents" / "default-roster.yaml") or {}
    for row in roster.get("agents", []) or []:
        if row.get("id") == agent_id:
            return row
    raise KeyError(f"agent not found in default roster: {agent_id}")


